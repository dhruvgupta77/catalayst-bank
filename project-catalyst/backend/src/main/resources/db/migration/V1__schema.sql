CREATE TABLE customers (
    id VARCHAR(20) PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    age INT NOT NULL,
    monthly_salary NUMERIC(15,2) NOT NULL,
    risk_profile VARCHAR(20) NOT NULL,
    monthly_loan_payment NUMERIC(15,2) NOT NULL,
    emergency_fund_target NUMERIC(15,2) NOT NULL,
    credit_score INT NOT NULL
);

CREATE TABLE accounts (
    id VARCHAR(30) PRIMARY KEY,
    customer_id VARCHAR(20) NOT NULL REFERENCES customers(id),
    type VARCHAR(30) NOT NULL,
    name VARCHAR(100) NOT NULL,
    balance NUMERIC(15,2) NOT NULL,
    interest_rate NUMERIC(6,2) NOT NULL DEFAULT 0
);

CREATE TABLE products (
    id VARCHAR(40) PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    category VARCHAR(30) NOT NULL,
    min_amount NUMERIC(15,2) NOT NULL,
    max_amount NUMERIC(15,2) NOT NULL,
    indicative_rate NUMERIC(6,2) NOT NULL,
    risk_level INT NOT NULL,
    description VARCHAR(400) NOT NULL
);

CREATE TABLE liquidity_events (
    id VARCHAR(30) PRIMARY KEY,
    idempotency_key VARCHAR(100) NOT NULL UNIQUE,
    correlation_id VARCHAR(40) NOT NULL,
    event_type VARCHAR(30) NOT NULL,
    customer_id VARCHAR(20) NOT NULL REFERENCES customers(id),
    amount NUMERIC(15,2) NOT NULL,
    currency VARCHAR(3) NOT NULL,
    source VARCHAR(40) NOT NULL,
    memo VARCHAR(200),
    status VARCHAR(20) NOT NULL,
    occurred_at TIMESTAMP WITH TIME ZONE NOT NULL,
    received_at TIMESTAMP WITH TIME ZONE NOT NULL,
    recommendation_id VARCHAR(30)
);

CREATE TABLE financial_context (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id VARCHAR(30) NOT NULL REFERENCES liquidity_events(id),
    customer_id VARCHAR(20) NOT NULL,
    context_json VARCHAR(8000) NOT NULL,
    reduced_context BOOLEAN NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE recommendations (
    id VARCHAR(30) PRIMARY KEY,
    event_id VARCHAR(30) NOT NULL REFERENCES liquidity_events(id),
    customer_id VARCHAR(20) NOT NULL,
    status VARCHAR(20) NOT NULL,
    source VARCHAR(40) NOT NULL,
    narrative_json VARCHAR(8000) NOT NULL,
    rules_json VARCHAR(8000) NOT NULL,
    reduced_context BOOLEAN NOT NULL,
    generation_ms BIGINT NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    viewed_at TIMESTAMP WITH TIME ZONE,
    decided_at TIMESTAMP WITH TIME ZONE
);

CREATE TABLE financial_actions (
    id VARCHAR(30) PRIMARY KEY,
    recommendation_id VARCHAR(30) NOT NULL REFERENCES recommendations(id),
    event_id VARCHAR(30) NOT NULL,
    customer_id VARCHAR(20) NOT NULL,
    action_type VARCHAR(30) NOT NULL,
    amount NUMERIC(15,2) NOT NULL,
    product_id VARCHAR(40),
    product_name VARCHAR(100),
    priority INT NOT NULL,
    reason VARCHAR(400) NOT NULL,
    impact VARCHAR(400),
    status VARCHAR(20) NOT NULL,
    progress INT NOT NULL DEFAULT 0,
    progress_note VARCHAR(200),
    failure_reason VARCHAR(400),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    executed_at TIMESTAMP WITH TIME ZONE
);

CREATE TABLE consents (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recommendation_id VARCHAR(30) NOT NULL,
    action_id VARCHAR(30) NOT NULL,
    customer_id VARCHAR(20) NOT NULL,
    statement VARCHAR(400) NOT NULL,
    actor VARCHAR(30) NOT NULL,
    channel VARCHAR(30) NOT NULL,
    granted_at TIMESTAMP WITH TIME ZONE NOT NULL,
    expires_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE audit_events (
    seq BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id VARCHAR(30) NOT NULL,
    customer_id VARCHAR(20) NOT NULL,
    correlation_id VARCHAR(40) NOT NULL,
    action VARCHAR(50) NOT NULL,
    actor VARCHAR(30) NOT NULL,
    result VARCHAR(20) NOT NULL,
    detail VARCHAR(1000),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_audit_event ON audit_events(event_id);
CREATE INDEX idx_actions_reco ON financial_actions(recommendation_id);
CREATE INDEX idx_events_customer ON liquidity_events(customer_id);
